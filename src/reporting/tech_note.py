"""Technical note (PDF, <= 4 pages) generated from summary.json + figures, so the numbers
in the note always match the latest pipeline run."""
from __future__ import annotations

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.platypus import Image, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from src.config import load_config, out_dir

ss = getSampleStyleSheet()
H1 = ParagraphStyle("h1", parent=ss["Heading2"], fontSize=11, spaceBefore=6, spaceAfter=2, textColor=colors.HexColor("#1f2d3d"))
TXT = ParagraphStyle("t", parent=ss["Normal"], fontSize=8, leading=10)
SMALL = ParagraphStyle("s", parent=TXT, fontSize=7, leading=8.6)
H2 = ParagraphStyle("h2", parent=H1, fontSize=9.5, spaceBefore=5, spaceAfter=1)
BULLET = ParagraphStyle("b", parent=TXT, leftIndent=11, bulletIndent=2, spaceAfter=1.5)
BULLET_SMALL = ParagraphStyle("bs", parent=SMALL, leftIndent=11, bulletIndent=2, spaceAfter=0.5)
W = A4[0] - 3 * cm


CELL = ParagraphStyle("c", parent=ss["Normal"], fontSize=7, leading=8.5)
CELL_B = ParagraphStyle("cb", parent=CELL, fontName="Helvetica-Bold")


def _tbl(rows, widths, bold_last=False):
    # wrap text cells so long assumptions break onto new lines instead of overflowing
    rows = [[Paragraph(str(c), CELL_B if (r == 0 or (bold_last and r == len(rows) - 1)) else CELL)
             if isinstance(c, str) else c for c in row] for r, row in enumerate(rows)]
    t = Table(rows, colWidths=widths)
    style = [("FONTSIZE", (0, 0), (-1, -1), 7), ("LEADING", (0, 0), (-1, -1), 8.5),
             ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#dfe6ee")), ("GRID", (0, 0), (-1, -1), 0.3, colors.grey),
             ("TOPPADDING", (0, 0), (-1, -1), 1.5), ("BOTTOMPADDING", (0, 0), (-1, -1), 1.5), ("VALIGN", (0, 0), (-1, -1), "TOP")]
    if bold_last:
        style.append(("FONTNAME", (0, -1), (-1, -1), "Helvetica-Bold"))
    t.setStyle(TableStyle(style))
    return t


def _img(name, width, ratio):
    return Image(str(out_dir() / name), width=width, height=width * ratio)


def P(text, st=TXT):
    return Paragraph(text, st)


def build(s: dict) -> None:
    cfg = load_config()
    th, fc, dga, hi, ml, adv, rag = (s["thermal_iec60076_7"], s["forecast"], s["dga"], s["health_index"],
                                     s["mlops"], s["advisory"], s["rag_eval"])
    tc = cfg["thermal"]
    el = [Paragraph("Power Transformer (10 MVA, 33/11 kV) Health Monitoring - Technical Note", ss["Title"]),
          Paragraph("Smeet Patel &nbsp;|&nbsp; October 2026", ParagraphStyle("by", parent=TXT, alignment=1, spaceAfter=4)),
          P("Prototype that detects early deterioration and tells maintenance what to do next. Public + synthetic data only. "
            "Every number below is regenerated by <font face='Courier'>python -m src.pipeline</font>; all assumptions live in "
            "<font face='Courier'>config.yaml</font>."),
          Paragraph("1. Architecture", H1), _img("fig_architecture.png", W * 0.92, 0.5)]

    el += [Paragraph("2. Data and key assumptions", H1), _tbl([
        ["Item", "Source / assumption"],
        ["Load, top-oil temp.", "ETTm1 (15-min, 2016-07-01..2018-06-26, 69,680 rows). HUFL magnitude scaled so its 99.5th percentile = 1.0 pu."],
        ["Ambient, V, I per phase, tap", "Synthetic (seeded): WMO monthly normals for Ahmadabad [R1] (Jan 20.1 C, May 34.5 C) +/-5 C daily; 3 % phase imbalance; OLTC 17 taps x 1.25 %. Verified by 9 plausibility tests (tests/test_synthetic.py)."],
        ["Transformer", f"10 MVA, 33/11 kV, Dyn11, ONAN, 175/525 A. IEC 60076-7 ONAN typical: x={tc['x']}, y={tc['y']}, R={tc['R']}, H={tc['H']}, "
                        f"gr={tc['gr_k']} K, top-oil rise {tc['delta_theta_or_k']} K, tau_o={tc['tau_o_min']:.0f} min, tau_w={tc['tau_w_min']:.0f} min; non-upgraded paper; life 180,000 h."],
        ["Alarms", f"OTI alarm/trip {tc['alarms']['oti_alarm_c']}/{tc['alarms']['oti_trip_c']} C, WTI alarm/trip {tc['alarms']['wti_alarm_c']}/{tc['alarms']['wti_trip_c']} C."],
        ["DGA labelled cases", f"589 literature cases (E. Li, IEEE DataPort 2019) -> {dga['data']['rows_final']} after removing {dga['data']['removed_overlap_with_iec_tc10']} "
                               f"cases that duplicate the IEC TC 10 set and {dga['data']['removed_duplicates']} duplicates. IEC TC 10 (Duval & dePablo 2001, 113 cases) = unseen test."],
        ["Unit DGA, oil, events", "Synthetic: daily online DGA (healthy, then T2 fault growing over last 150 days), quarterly moisture/BDV drift, Buchholz alarm 10 days before end."],
        ["Costs", "INR: failure = 60 lakh repair + 720 h x 40k/h outage; action = 3.5 lakh inspection/oil treatment + 24 h outage; PoF by band 0.5-30 %."],
    ], [3.3 * cm, W - 3.3 * cm])]

    # ---- thermal
    b = fc["baselines_test"]
    rows = [["Model (test 2018-01..06)", "MAE (C)", "RMSE (C)"]]
    for k, v in b.items():
        rows.append([k, f"{v['MAE']:.3f}", f"{v['RMSE']:.3f}"])
    rows.append(["XGBoost causal (past data only)", f"{fc['causal']['test']['MAE']:.3f}", f"{fc['causal']['test']['RMSE']:.3f}"])
    rows.append(["XGBoost + day-ahead load forecast", f"{fc['day_ahead']['test']['MAE']:.3f}", f"{fc['day_ahead']['test']['RMSE']:.3f}"])
    el += [Paragraph("3. Thermal analytics", H1),
           P(f"Direct 96-step (24 h) forecast of the change in OT with level-free features (lags/rolling stats relative to current OT, load deviations, calendar). "
             f"Time split train {fc['split']['train'][0][:10]}..{fc['split']['train'][1][:10]}, validation Nov-Dec 2017, test 2018 with a 24 h gap. "
             f"Persistence is the hard baseline: the causal model only ties it on MAE ({fc['causal']['MAE_improvement_vs_best_baseline_pct']:+.1f} %) but cuts RMSE "
             f"({100 * (1 - fc['causal']['test']['RMSE'] / b['Persistence (24 h seasonal naive)']['RMSE']):.1f} %); with a day-ahead load forecast "
             f"(simulated, 5 % error) MAE improves {fc['day_ahead']['MAE_improvement_vs_best_baseline_pct']:.1f} %. ETT has no weather inputs, which bounds the skill."),
           _tbl(rows, [8 * cm, 2.5 * cm, 2.5 * cm], bold_last=True), Spacer(1, 3),
           _img("fig_forecast.png", W, 0.375),
           P(f"<b>IEC 60076-7</b> difference-equation model (5-min sub-steps) on the scaled ETT load and synthetic ambient: max top-oil "
             f"{th['max_top_oil_c']:.1f} C, max hot-spot {th['max_hot_spot_c']:.1f} C (99th pct {th['p99_hot_spot_c']:.1f} C). Relative ageing V = 2^((theta_h-98)/6); "
             f"loss of life {th['loss_of_life_hours']:,.0f} h over {th['period_hours']:,.0f} h (equivalent ageing factor {th['equivalent_ageing_factor']:.2f}, "
             f"{th['life_consumed_pct']:.2f} % of normal life). Ageing is concentrated in a few overload peaks."),
           _img("fig_thermal.png", W * 0.9, 0.525)]

    # ---- DGA
    cv = dga["cv"]
    sel = dga["selected_model"]
    rows = [["Method (5-fold stratified CV, n=%d)" % dga["data"]["rows_final"], "Macro-F1", "Accuracy"]]
    for k, v in cv.items():
        rows.append([k + ("  <- selected" if k == sel else ""), f"{v['macro_f1']:.3f}", f"{v['accuracy']:.3f}"])
    pc = cv[sel]["per_class"]
    rows2 = [["Class", "Precision", "Recall", "F1", "Support"]] + [[c, f"{v['precision']:.2f}", f"{v['recall']:.2f}", f"{v['f1-score']:.2f}", int(v["support"])] for c, v in pc.items()]
    t10 = dga["iec_tc10"]
    el += [Paragraph("4. DGA fault diagnosis", H1),
           P("Baseline: Duval Triangle 1 (IEC 60599) zones PD/T1/T2/T3/D1/D2/DT; a pre-screen labels samples Normal when all gases are below IEC 60599 typical values "
             "(the triangle alone always returns a fault). ML features are scale-free: relative gas composition, Duval percentages, log IEC ratios, log TDCG. "
             "<b>Class imbalance</b> (largest/smallest class %.1fx): compared no handling, class-balanced sample weights, SMOTE inside training folds only, and a balanced random forest; "
             "selection on macro-F1 so minority faults (T2, PD) count equally." % (max(dga['data']['class_counts'].values()) / min(dga['data']['class_counts'].values()))),
           Table([[_tbl(rows, [6.4 * cm, 1.7 * cm, 1.7 * cm]), _tbl(rows2, [1.1 * cm, 1.6 * cm, 1.3 * cm, 1.0 * cm, 1.5 * cm])]],
                 colWidths=[10.2 * cm, 6.8 * cm], style=[("VALIGN", (0, 0), (-1, -1), "TOP")]),
           Spacer(1, 3), _img("fig_dga_confusion.png", W * 0.85, 0.44),
           P(f"<b>Unseen IEC TC 10 benchmark</b> (n={t10['n']}, T1+T2 merged as in the database): Duval Triangle 1 macro-F1 {t10['Duval Triangle 1']['macro_f1']:.2f} "
             f"(accuracy {t10['Duval Triangle 1']['accuracy']:.2f}) vs ML {t10['ML']['macro_f1']:.2f} ({t10['ML']['accuracy']:.2f}). Duval was calibrated on exactly these "
             f"cases, so it wins there, while the ML model is far better on the broader, noisier literature set ({cv[sel]['macro_f1']:.2f} vs {cv['Duval Triangle 1 (rule-based)']['macro_f1']:.2f}). "
             "In production both are reported; disagreement is flagged for an expert.")]

    # ---- health index
    lat = hi["latest"]
    det = hi["detection"]
    W_ = cfg["health_index"]["weights"]
    drv = "; ".join(f"{d['parameter']} = {d['value']} (-{d['points_lost']})" for d in lat["top_drivers"])
    el += [Paragraph("5. Health index", H1),
           P(f"HI = {W_['dga']:.2f} DGA + {W_['thermal']:.2f} Thermal + {W_['oil']:.2f} Oil + {W_['loading']:.2f} Loading. Each parameter is scored linearly between a "
             "'good' (100) and 'bad' (0) limit (IEC 60599 typical gas values, IEC 60422 oil limits, IEC 60076-7 hot-spot 98/140 C, ageing rate, alarms, overload hours); "
             "gas weights follow Jahromi et al. (2009). DGA fault severity caps the DGA score and (100 - 55 x severity) the whole HI, so an active fault is never 'Good'; Buchholz/PRD events cap the HI. Because HI = 100 - sum of points lost, the "
             "<b>top-3 drivers</b> are the parameters that lost most points. Bands: Very Good >= 85, Good 70-85, Fair 50-70, Poor 30-50, Very Poor < 30."),
           P(f"Latest ({adv['as_of']}): <b>HI {lat['health_index']} - {lat['band']}</b>; components {lat['components']}; drivers: {drv}. "
             f"DGA: ML {lat['dga_diagnosis']['ml_class']} (p={lat['dga_diagnosis']['ml_probability']}), Duval {lat['dga_diagnosis']['duval_triangle_1']}."),
           _img("fig_detection_timeline.png", W * 0.88, 0.575),
           P(f"<b>Early detection</b> (synthetic T2 fault starting {det['fault_onset']}): DGA flagged abnormal on {det['first_dga_abnormal']} "
             f"(ML {det['ml_class_at_detection']}, Duval {det['duval_at_detection']}), band Fair from {det['first_band_fair_or_worse']} - "
             f"<b>{det['lead_days_before_buchholz']} days before the Buchholz alarm</b> ({det['buchholz_alarm']}). "
             f"{det['pre_onset_dga_false_alarms']} DGA false alarms in the {det['pre_onset_days']} healthy days before the fault.")]

    # ---- MLOps
    perf = ml["forecast_performance_drift"]
    psi = ", ".join(f"{k} {v['psi']}" for k, v in ml["data_drift_last_30d_vs_train"].items())
    el += [Paragraph("6. Deployment and MLOps", H1),
           P("<b>Serving:</b> FastAPI in Docker (<font face='Courier'>docker compose up --build</font> trains, then serves; verified on Docker Desktop 28 / Windows 11; "
             "the container uses the host's local Ollama, or a containerised one with <font face='Courier'>--profile ollama</font>). "
             "<font face='Courier'>POST /health-index</font> takes thermal, loading, DGA, oil and event inputs and returns score, band, components, top-3 drivers and DGA diagnosis; "
             "<font face='Courier'>GET /health-index/latest</font>, <font face='Courier'>POST /ask</font> (RAG), <font face='Courier'>GET /assistant</font> (chat page), "
             "<font face='Courier'>GET /healthz</font>, OpenAPI at /docs. "
             f"<b>Versioning:</b> models/&lt;name&gt;/&lt;semver&gt;/ with model.joblib + metadata.json (config SHA-256, data-file fingerprints, metrics, features) and a LATEST pointer "
             "(rollback = edit one file); API responses carry the model version; Git tags tie code to model versions. "
             f"<b>Drift:</b> (1) PSI per key input, last 30 days vs the same 30 days one year earlier (so normal seasonality is not flagged), threshold "
             f"{cfg['mlops']['drift']['psi_threshold']} - now: {psi}. This is genuine drift: mean OT fell from {ml['drift_context']['ot_mean_reference']} C to "
             f"{ml['drift_context']['ot_mean_recent']} C year-on-year, so the retraining trigger fires; "
             f"(2) rolling {cfg['mlops']['drift']['rolling_days']}-day forecast MAE / validation MAE, threshold {perf['threshold_ratio']}x - max {perf['max_ratio']}x, "
             f"{perf['days_in_breach']} days in breach during 2018; (3) ML-vs-Duval disagreement rate on new DGA. "
             "<b>Retraining triggers:</b> any PSI breach on a key input; MAE ratio breach for 3 consecutive days; >= 25 new inspection-confirmed DGA cases; quarterly schedule; "
             "new models are promoted only if they beat the served model on the latest hold-out window."),
           _img("fig_drift.png", W * 0.85, 0.3)]

    # ---- advisory + RAG
    cb = adv["cost_benefit"]
    ok = sum(r["correct_behaviour"] for r in rag["rows"])
    el += [Paragraph("7. Maintenance advisory and RAG assistant", H1),
           P(f"<b>Advisory</b> (reports/maintenance_advisory.pdf, one page): band {adv['band']}, urgency {adv['urgency']}; top risk: {adv['top_risk']}. "
             f"Expected 12-month loss without action INR {cb['expected_loss_no_action_inr'] / 1e5:.1f} lakh vs action cost INR {cb['action_cost_inr'] / 1e5:.1f} lakh; "
             f"net benefit INR {cb['net_benefit_inr'] / 1e5:.1f} lakh (B/C {cb['benefit_cost_ratio']:.1f})."),
           P(f"<b>RAG</b>: 494 chunks from USBR FIST 3-30/3-31, TF-IDF retrieval, answers by a locally hosted open-source LLM "
             f"({cfg['rag']['llm_model']} via Ollama - no external API, per client requirement) constrained to retrieved text with [n] citations, "
             f"or extractive quotes when the local model is not running. Guardrails: domain-term and similarity threshold refusal, 'INSUFFICIENT_CONTEXT' refusal from the model, "
             f"sentence-level grounding check (each sentence must cite [n], and its content words (>= 60 %) and all its numbers must appear in the cited chunk), safety notice. "
             f"A 3B model can still mis-read garbled PDF tables or echo a wrong premise in the question; those pass the lexical check (see limitations). Answer/refuse decisions correct on {ok}/{len(rag['rows'])} test questions.")]

    limitations = [
        "<b>Data realism:</b> ETT is a different (Chinese) transformer with unknown rating and no weather data. The scaled load, all oil, DGA "
        "and event data for the monitored unit, and the costs are synthetic or assumed, so the health-index levels demonstrate the method, "
        "not this asset's true condition.",
        "<b>Thermal model:</b> IEC 60076-7 parameters are typical values, not factory heat-run data; WTI is computed, not measured.",
        "<b>DGA training data:</b> compiled from literature with heterogeneous labelling; the Duval DT zone and 'Normal' have no training "
        "labels; CO/CO2 are not used by the classifier.",
        "<b>Health-index calibration:</b> weights, limits and failure probabilities are expert assumptions that need calibration "
        "against utility failure and inspection records.",
        "<b>Forecast:</b> without weather inputs the causal model only ties persistence on MAE.",
        "<b>RAG corpus:</b> two US manuals (2000/2003); IEC/IEEE standards are not included (paywalled).",
        "<b>Local LLM:</b> the 3B model runs on CPU (8-40 s per answer) and the grounding check is lexical, so semantic errors "
        "(wrong table row, accepted false premise) are possible.",
    ]
    references = [
        "[R1] WMO climate normals, Ahmadabad 42647 (JMA Tokyo Climate Center)",
        "[R2] Duval &amp; dePablo, IEEE EI Magazine 17(2), 2001 - IEC 60599 typical values, IEC TC 10 data",
        "[R3] USBR FIST 3-30 Transformer Maintenance (2000)",
        "[R4] USBR FIST 3-31 Transformer Diagnostics (2003) - TDCG rates, C2H2 guidance",
        "[R5] Kunicki et al., Energies 12:3561, 2019",
        "[R6] IEC 60422:2013 water limits (secondary source)",
        "[R7] Vaisala, moisture vs BDV white paper",
        "[R8] Jahromi et al., IEEE EI Magazine, 2009",
        "[R9] Utility alarm-setting practice (assumption)",
        "IEC 60076-7:2018, IEC 60599 Annex B and IEC 60422 BDV tables are paywalled and were not re-checked; "
        "per-value verification status is listed in the README",
    ]
    el += [Paragraph("8. Limitations", H1)]
    el += [Paragraph(t, BULLET, bulletText="•") for t in limitations]
    el += [Paragraph("AI-assistant disclosure", H2),
           P("Claude Code was used to draft code, tests and this note; all design choices, assumptions and results were reviewed by the "
             "author, who can explain and modify every part."),
           Paragraph("References", H2)]
    el += [Paragraph(t, BULLET_SMALL, bulletText="•") for t in references]

    doc = SimpleDocTemplate(str(out_dir("reports_dir") / "technical_note.pdf"), pagesize=A4, leftMargin=1.5 * cm,
                            rightMargin=1.5 * cm, topMargin=1.2 * cm, bottomMargin=1.2 * cm,
                            title="Transformer Health Monitoring - Technical Note")
    doc.build(el)
